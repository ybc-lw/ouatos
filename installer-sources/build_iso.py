#!/usr/bin/env python3
"""Builds the ouatos installer ISO from a rootfs .tar.xz.

usage: build_iso.py ROOTFS.tar.xz OUTPUT.iso [--work DIR]

Needs root (chroot/mount), Python 3 with Pillow (font atlas), mke2fs (bundled into the installer), and
nothing else: ISO 9660, El Torito, FAT and cpio are written by the code in build/.
"""
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(HERE, 'installer'), os.path.join(HERE, 'build')]
import engine
import fatfs
import gen_font
import isowriter
import mklive
import rootfs_info

BIOS_MODS = ['biosdisk', 'iso9660', 'part_msdos', 'part_gpt', 'search', 'search_label', 'search_fs_file', 'normal',
             'configfile', 'linux', 'boot', 'echo', 'test', 'gzio']
EFI_MODS = ['iso9660', 'fat', 'part_msdos', 'part_gpt', 'search', 'search_label', 'search_fs_file', 'normal',
            'configfile', 'linux', 'boot', 'echo', 'test', 'gzio', 'efi_gop', 'all_video']
EARLY_CFG = ('# find the installation medium by its volume label, wherever firmware put us\n'
             'if search --no-floppy --label --set=root %s; then\n  set prefix=($root)/boot/grub\nfi\n')


def step(msg):
    print('\n==> ' + msg, flush=True)


def run(cmd, **kw):
    r = subprocess.run(cmd, **kw)
    if r.returncode:
        raise SystemExit('command failed: %s' % ' '.join(map(str, cmd)))
    return r


def unmount_under(path):
    """Never let a stale bind mount (/dev, /proc ...) inside the work dir be traversed by rmtree."""
    path = os.path.realpath(path)
    mounts = [l.split()[1] for l in open('/proc/mounts') if l.split()[1].startswith(path + '/')]
    for m in sorted(mounts, key=len, reverse=True):
        subprocess.run(['umount', '-l', m])


def grub_cfg(sysname, label):
    entries = [('Install ' + sysname, ''), ('Install %s (text mode)' % sysname, ' ouatos.text=1'),
               ('Debug shell (no installer)', ' ouatos.shell=1')]
    cfg = ['# Boot menu of the %s installer (generated by build_iso.py)' % engine.BRAND,
           'set timeout=5', 'set default=0', 'insmod all_video', 'insmod font',
           'if loadfont /boot/grub/fonts/unicode.pf2; then',
           '  insmod gfxterm',
           '  set gfxmode=1920x1080,1366x768,1280x720,1024x768,auto',
           '  set gfxpayload=keep',
           '  terminal_output gfxterm',
           'fi', 'set menu_color_normal=light-gray/black', 'set menu_color_highlight=white/blue', '']
    for title, extra in entries:
        cfg += ["menuentry '%s' --class %s {" % (title, engine.BRAND),
                '  linux /boot/vmlinuz quiet loglevel=3%s' % extra,
                '  initrd /boot/initrd.img', '}']
    cfg += ["menuentry 'Restart' {", '  insmod reboot', '  reboot', '}',
            "menuentry 'Power off' {", '  insmod halt', '  halt', '}', '']
    return '\n'.join(cfg)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    work = '/tmp/ouatos-build'
    if '--work' in sys.argv:
        work = sys.argv[sys.argv.index('--work') + 1]
        args = [a for a in args if a != work]
    if len(args) != 2:
        raise SystemExit(__doc__)
    tarball, out_iso = args
    t0 = time.time()
    rootfs, live, iso_dir = [os.path.join(work, d) for d in ('rootfs', 'live', 'iso')]
    os.makedirs(work, exist_ok=True)
    unmount_under(work)

    step('Reading the OS image (%s)' % tarball)
    info = rootfs_info.make_rootfs_info(tarball)
    osr, kver = info['os_release'], info['kernel']
    sysname, brand = engine.system_name(osr), engine.brand_name(osr)
    label = engine.ISO_LABEL
    print('   system name : %s   (from /usr/lib/os-release; brand "%s")' % (sysname, brand))
    print('   kernel      : %s   installed size: %d MiB' % (kver, info['installed_bytes'] >> 20))
    for f in info.get('lfs_pointers', []):
        print('\n   *** WARNING: %s is a Git LFS pointer file, not the real file (%.1f MiB expected).\n'
              '   *** The image was built without `git lfs pull`; the installed system will contain the stub.\n'
              % (f['path'], (f['expected_bytes'] or 0) / 2**20))

    step('Unpacking the OS image to use its kernel, GRUB, Python and tools')
    if os.path.exists(rootfs):
        shutil.rmtree(rootfs)
    os.makedirs(rootfs)
    run(['tar', '-xf', tarball, '-C', rootfs, '--numeric-owner', '--xattrs', '--xattrs-include=*'],
        env=dict(os.environ, XZ_OPT='-T0'))
    # the builtin xz support of tar needs the xz binary; fall back to Python if it is missing
    if not os.path.exists(os.path.join(rootfs, 'usr/lib/os-release')):
        raise SystemExit('extraction failed')

    step('Rendering the installer font atlas')
    gen_font.main(os.path.join(HERE, 'installer', 'font.bin'))

    step('Building the live installer environment')
    mklive.build_live(rootfs, live, kver, os.path.join(HERE, 'installer'))
    if os.path.exists(iso_dir):
        shutil.rmtree(iso_dir)
    for d in ('boot/grub/fonts', 'ouatos/licenses', 'EFI/BOOT'):
        os.makedirs(os.path.join(iso_dir, d))
    n = mklive.write_cpio_gz(live, os.path.join(iso_dir, 'boot/initrd.img'),
                             [('dev/console', 0o020600, 5, 1), ('dev/null', 0o020666, 1, 3)])
    print('   initramfs: %.1f MiB' % (n / 2**20))
    shutil.copy2(os.path.join(rootfs, 'boot', 'vmlinuz-' + kver), os.path.join(iso_dir, 'boot/vmlinuz'))

    step('Building the bootloader images with the OS image\'s own GRUB')
    ob = os.path.join(rootfs, 'tmp/ob')
    os.makedirs(ob, exist_ok=True)
    open(os.path.join(ob, 'early.cfg'), 'w').write(EARLY_CFG % label)
    gfx = {}
    for plat, fmt, out, mods in (('i386-pc', 'i386-pc-eltorito', 'eltorito.img', BIOS_MODS),
                                 ('x86_64-efi', 'x86_64-efi', 'bootx64.efi', EFI_MODS)):
        have = [m for m in mods if os.path.exists(os.path.join(rootfs, 'usr/lib/grub', plat, m + '.mod'))]
        run(['chroot', rootfs, '/usr/bin/grub-mkimage', '-O', fmt, '-d', '/usr/lib/grub/' + plat, '-o', '/tmp/ob/' + out,
             '-p', '/boot/grub', '-c', '/tmp/ob/early.cfg'] + have)
        gfx[out] = open(os.path.join(ob, out), 'rb').read()
        d = os.path.join(iso_dir, 'boot/grub', plat)
        os.makedirs(d)
        src = os.path.join(rootfs, 'usr/lib/grub', plat)
        for f in sorted(os.listdir(src)):
            if f.endswith(('.mod', '.lst')):
                shutil.copy2(os.path.join(src, f), d)
        print('   %-14s %6d bytes  (%d modules embedded)' % (out, len(gfx[out]), len(have)))
    shutil.copy2(os.path.join(rootfs, 'usr/share/grub/unicode.pf2'), os.path.join(iso_dir, 'boot/grub/fonts/unicode.pf2'))
    cfg = grub_cfg(sysname, label)
    open(os.path.join(ob, 'grub.cfg'), 'w').write(cfg)
    run(['chroot', rootfs, '/usr/bin/grub-script-check', '/tmp/ob/grub.cfg'])
    print('   grub.cfg passes grub-script-check')
    open(os.path.join(iso_dir, 'boot/grub/grub.cfg'), 'w').write(cfg)

    step('Building the EFI boot image (FAT)')
    efi = gfx['bootx64.efi']
    size = max(4, -(-(len(efi) + 600 * 1024) // (1 << 20))) << 20
    espimg = fatfs.make_fat_image({'EFI/BOOT/BOOTX64.EFI': efi}, size, fat_bits=16, label='OUATOSEFI',
                                  mtime=int(time.time()))
    print('   efi.img: %d MiB FAT16' % (size >> 20))

    step('Collecting installer payload and notices')
    with open(os.path.join(iso_dir, 'ouatos/os_release'), 'w') as f:
        f.write(open(os.path.join(rootfs, 'usr/lib/os-release')).read())
    json.dump(info, open(os.path.join(iso_dir, 'ouatos/rootfsinfo.json'), 'w'))
    for src, name in (('/usr/share/doc/fonts-dejavu-core/copyright', 'DejaVu-fonts.txt'),
                      ('/usr/share/doc/e2fsprogs/copyright', 'e2fsprogs.txt'),
                      (os.path.join(rootfs, 'usr/share/doc/grub-common/copyright'), 'grub.txt'),
                      (os.path.join(rootfs, 'usr/share/doc/linux-image-%s/copyright' % kver), 'linux-kernel.txt')):
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(iso_dir, 'ouatos/licenses', name))
    open(os.path.join(iso_dir, 'ouatos/README.txt'), 'w').write(
        '%s installer medium\n\n'
        'Boots on BIOS and UEFI (Secure Boot must be off: the bootloader is unsigned) and installs %s.\n'
        'Contents: boot/ (kernel, installer initramfs, GRUB), ouatos/rootfs.txz (the system that gets installed, your rootfs.tar.xz unchanged).\n'
        'Third-party notices: ouatos/licenses/.\n' % (sysname, sysname))

    step('Writing the ISO 9660 image')
    iso = isowriter.ISO(label, sysid='LINUX', publisher=brand, preparer='build_iso.py',
                        app='%s installer' % brand, mtime=int(time.time()))
    iso.mkdir('/boot/grub')
    for root_, _, files in os.walk(iso_dir):
        for f in sorted(files):
            p = os.path.join(root_, f)
            rel = '/' + os.path.relpath(p, iso_dir)
            iso.add_file(rel, src=p)
    iso.add_file('/boot/grub/i386-pc/eltorito.img', data=gfx['eltorito.img'])
    iso.add_file('/boot/grub/efi.img', data=espimg)
    iso.add_file('/EFI/BOOT/BOOTX64.EFI', data=efi)
    iso.add_file('/ouatos/rootfs.txz', src=tarball)   # ISO-safe name: reads the same with or without Rock Ridge
    r = iso.build(out_iso, bios_boot='/boot/grub/i386-pc/eltorito.img', efi_boot='/boot/grub/efi.img')
    print('   %s: %.1f MiB, %d sectors, %d directories' % (out_iso, os.path.getsize(out_iso) / 2**20, r['total_sectors'], r['dirs']))
    shutil.rmtree(ob, ignore_errors=True)
    print('\nDone in %.0f s.' % (time.time() - t0))


if __name__ == '__main__':
    main()
